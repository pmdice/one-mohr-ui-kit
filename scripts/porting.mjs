// Writes handbook/porting.generated.ts from the "Übertragen" sections of all rule pages.
// Run after changing a rule: node scripts/porting.mjs
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs"
import path from "node:path"
import { extractPorting } from "../handbook/porting-extract.mjs"

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "../handbook")
const entries = readdirSync(root)
    .filter((d) => statSync(path.join(root, d)).isDirectory())
    .flatMap((d) => readdirSync(path.join(root, d)).filter((f) => /^[A-Z]-\d{2}.*\.mdx$/.test(f)).map((f) => path.join(root, d, f)))
    .map((f) => extractPorting(readFileSync(f, "utf8")))
    .filter(Boolean)
    .sort((a, b) => a.id.localeCompare(b.id))
writeFileSync(
    path.join(root, "porting.generated.ts"),
    `// Generated by scripts/porting.mjs from the rule pages. Do not edit by hand.\n\nexport const PORTING: { id: string; title: string; notes: string[] }[] = ${JSON.stringify(entries, null, 4)}\n`
)
console.log(`${entries.length} rules`)
